// Command gen writes internal/zonetrigger/table.go from a LostCityRS Content checkout (branch 289):
// every [zone,...], [zoneexit,...], [mapzone,...] and [mapzoneexit,...] trigger script's location.
//
//	go run ./internal/zonetrigger/gen -content ../content
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// trigger matches a trigger script's label at the start of a line: a map square is
// level_mx_mz, a zone level_mx_mz_lx_lz (lx and lz its tile offset inside the square).
var trigger = regexp.MustCompile(`^\[(mapzone|mapzoneexit|zone|zoneexit),(\d+)_(\d+)_(\d+)(?:_(\d+)_(\d+))?\]`)

func main() {
	content := flag.String("content", "", "LostCityRS Content checkout (branch 289)")
	out := flag.String("out", "internal/zonetrigger/table.go", "file to write")
	flag.Parse()
	if *content == "" {
		log.Fatal("-content is required")
	}
	keys := map[string]map[uint32]string{"mapzone": {}, "mapzoneexit": {}, "zone": {}, "zoneexit": {}}
	root := filepath.Join(*content, "scripts")
	err := filepath.WalkDir(root, func(path string, e fs.DirEntry, err error) error {
		if err != nil || e.IsDir() || !strings.HasSuffix(path, ".rs2") {
			return err
		}
		f, err := os.Open(path)
		if err != nil {
			return err
		}
		defer f.Close()
		sc := bufio.NewScanner(f)
		sc.Buffer(make([]byte, 1<<20), 1<<20)
		for sc.Scan() {
			m := trigger.FindStringSubmatch(sc.Text())
			if m == nil {
				continue
			}
			n := func(i int) uint32 { v, _ := strconv.Atoi(m[i]); return uint32(v) }
			name := m[2] + "_" + m[3] + "_" + m[4]
			switch m[1] {
			case "mapzone", "mapzoneexit":
				if m[5] != "" {
					return fmt.Errorf("%s: a map-square trigger with a zone offset: %s", path, m[0])
				}
				keys[m[1]][n(3)<<8|n(4)] = name
			default:
				if m[5] == "" {
					return fmt.Errorf("%s: a zone trigger with no zone offset: %s", path, m[0])
				}
				x, z := n(3)*64+n(5), n(4)*64+n(6)
				keys[m[1]][n(2)<<24|(x>>3)<<12|z>>3] = name + "_" + m[5] + "_" + m[6]
			}
		}
		return sc.Err()
	})
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/zonetrigger/gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package zonetrigger\n\n")
	fmt.Fprintf(&b, "// From LostCityRS Content 289: %d [mapzone], %d [mapzoneexit], %d [zone] and %d [zoneexit] triggers.\n\n",
		len(keys["mapzone"]), len(keys["mapzoneexit"]), len(keys["zone"]), len(keys["zoneexit"]))
	for _, v := range []struct{ name, kind string }{
		{"mapzoneEnter", "mapzone"}, {"mapzoneExit", "mapzoneexit"}, {"zoneEnter", "zone"}, {"zoneExit", "zoneexit"},
	} {
		ks := make([]uint32, 0, len(keys[v.kind]))
		for k := range keys[v.kind] {
			ks = append(ks, k)
		}
		sort.Slice(ks, func(i, j int) bool { return ks[i] < ks[j] })
		fmt.Fprintf(&b, "var %s = set(\n", v.name)
		for _, k := range ks {
			fmt.Fprintf(&b, "\t%#x, // %s\n", k, keys[v.kind][k])
		}
		fmt.Fprintf(&b, ")\n\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
