// Package webwalk is long-distance walking: a transport graph of doors, gates, stairs,
// ladders, ships and gangplanks laid over the collision pack, a route search across levels
// and regions, and a walk executor that follows a route with the TS walker's escalation
// ladder. It is a port of the TypeScript rsb0t client's src/bot/event/webwalk
// (PathFinder.ts, WalkExecutor.ts, walkLadder.ts, exec/doorCrossing.ts, exec/transportLoc.ts)
// and api/walking/Traversal.ts's walkResilient.
//
// The package has no client imports. Planning (Graph, Planner, Route) is pure; Walker runs
// a route through the Client interface, which internal/webwalk/live implements over
// actions, gamestate, locindex and chatlog.
//
// # Data
//
// graph.json is the TS graph exactly as PathFinder.addEdges compiles it: doors.json (each
// door both ways), transports.json after the state-aware activations, the curated travel
// catalog, and stairEdges.json, with each edge's plan-time requires and any special crossing
// (tolls, fares, dialogue gates) already resolved. It is generated by
// webwalk_reference_vector.ts at the repo root from the rsb0t TS checkout (MIT licensed,
// the commit is in the file's "source" field), and is data, not code. Edges whose tiles are
// not walkable in the pack are dropped when a Planner is built, as addEdges does.
//
// Live evidence wins over the baked data: ApproachOverrides moves an edge's stand tile to the
// one a live test proved the server accepts (the Ardougne ship ladder and the Port Sarim
// ladder, found with cmd/guidecrash -testloc; the Seers wheelhouse ladder, found by the
// crafter port).
//
// # Differences from the TS planner
//
//   - Heuristic. The TS search drops to Dijkstra whenever any edge spans more tiles than it
//     costs (ships, dungeon z±6400). This one uses min(Chebyshev to the goal, L), where L is
//     the cheapest (cost + Chebyshev from landing to goal) over those long edges. Any route
//     either uses no long edge, so it costs at least the Chebyshev distance, or its last long
//     edge e leaves it costing at least e.cost + Chebyshev(e.to, goal) >= L. The bound is
//     admissible and consistent, so routes cost the same as the TS planner's, with far fewer
//     expansions when the goal is not near a landing. L alone is weak when a dungeon ladder
//     lands near the goal, so the search also bounds a route through each long edge by the walk
//     to its entrance (Planner.heuristic); routes still cost what Dijkstra's do.
//   - No teleport catalog or essence-mine session state. Essence-mine exits and every other
//     special crossing need a Handler to execute (internal/webwalk/hops runs NPC fares and
//     dialogue crossings), so the planner leaves them out unless the caller allows them.
//   - Danger zones are data/dangerZones.ts's catalog and outside-in rule, plus a Wilderness
//     zone the TS catalog lacks. A Client that implements CombatClient adds what TS does not:
//     running and fleeing under attack (WalkOptions.Combat, off by default) and stopping
//     with OutcomeDied instead of replanning from the respawn. A Client that implements
//     HostileClient adds the other half TS has no answer for: breaking off from a
//     permanently-spawned hostile (a giant bat, a White wolf) BEFORE it engages
//     (WalkOptions.AvoidHostiles, also off by default), which is the only thing that helps a
//     combat-level-3 account, since by the time a hitmark exists the fight is already lost.
//   - The pack is static, so a Client that implements WallClient reports the walls live loc
//     changes add (an opened door's leaves), and the Walker learns single steps the server
//     refused. TS reads the live scene's collision flags for the same purpose.
//   - EdgeCorrections fix the graph's loc edges that disagree with the 289 map files.
//   - Requires fail open without a WorldState, as PathFinder does offline; a Walker should
//     pass one.
